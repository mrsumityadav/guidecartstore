// Helper functions for static queries
export function getAllProducts(): Product[] {
  return products.filter((p) => p.published);
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug.toLowerCase() === slug.toLowerCase() && p.published);
}

export function getFeaturedProducts(limit = 4): Product[] {
  return products.filter((p) => p.published && p.featured).slice(0, limit);
}

export function getBestsellerProducts(limit = 4): Product[] {
  return products.filter((p) => p.published && p.bestseller).slice(0, limit);
}

export function getProductsByCategory(categoryName: string): Product[] {
  return products.filter(
    (p) => p.published && p.category.toLowerCase() === categoryName.toLowerCase()
  );
}

export function getRelatedProducts(categoryName: string, currentSlug: string, limit = 4): Product[] {
  return products
    .filter(
      (p) =>
        p.published &&
        p.category.toLowerCase() === categoryName.toLowerCase() &&
        p.slug.toLowerCase() !== currentSlug.toLowerCase()
    )
    .slice(0, limit);
}
